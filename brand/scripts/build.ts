/**
 * Builds the brand files from the masters in `brand/masters/` (read by
 * `logo.ts`): writes the SVGs to
 * `brand/`, renders the PNG and ICO files to `brand/png/`, copies the favicon
 * and lockup files into the admin UI and the docs site, and writes the admin
 * UI's inline logo shapes (`logo-shapes.gen.ts`).
 *
 * Usage: bun run brand:build
 */
import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { faviconFrames } from './favicon.ts';
import {
  brandSvgs,
  COLORS,
  iconSvg,
  lockupShapes,
  lockupViewBox,
  symbolViewBox,
} from './logo.ts';
import { withRenderer } from './render.ts';

const brand = dirname(import.meta.dir);
const repo = dirname(brand);
const png = join(brand, 'png');

/**
 * Packs PNG images into an ICO file. Each entry stores the PNG as it is,
 * which every current browser and Windows since Vista read.
 */
function ico(frames: ReadonlyMap<number, Uint8Array>): Uint8Array {
  const entries = [...frames];
  const header = 6 + 16 * entries.length;
  const size = header + entries.reduce((n, [, data]) => n + data.length, 0);
  const out = new Uint8Array(size);
  const view = new DataView(out.buffer);
  view.setUint16(2, 1, true);
  view.setUint16(4, entries.length, true);
  let offset = header;
  entries.forEach(([px, data], i) => {
    const entry = 6 + 16 * i;
    view.setUint8(entry, px >= 256 ? 0 : px);
    view.setUint8(entry + 1, px >= 256 ? 0 : px);
    view.setUint16(entry + 4, 1, true);
    view.setUint16(entry + 6, 32, true);
    view.setUint32(entry + 8, data.length, true);
    view.setUint32(entry + 12, offset, true);
    out.set(data, offset);
    offset += data.length;
  });
  return out;
}

const written: string[] = [];
async function write(path: string, data: string | Uint8Array) {
  await writeFile(path, data);
  written.push(relative(repo, path));
}

for (const [name, svg] of Object.entries(brandSvgs())) {
  await write(join(brand, name), svg);
}

await mkdir(png, { recursive: true });
await withRenderer(async (r) => {
  await write(join(png, 'favicon.ico'), ico(await faviconFrames(r)));
  // iOS rounds the corners itself and shows transparency as black.
  await write(
    join(png, 'apple-touch-icon.png'),
    await r.png(iconSvg(), 180, 180, COLORS.violet),
  );
  for (const size of [192, 512]) {
    await write(
      join(png, `icon-${size}.png`),
      await r.png(iconSvg(), size, size),
    );
  }
});

const copies: Record<string, readonly string[]> = {
  'packages/server/admin-ui/public': [
    'goodnight-web-favicon.svg:favicon.svg',
    'png/favicon.ico:favicon.ico',
    'png/apple-touch-icon.png:apple-touch-icon.png',
  ],
  'apps/docs/public': [
    'goodnight-web-favicon.svg:favicon.svg',
    'png/favicon.ico:favicon.ico',
    'png/apple-touch-icon.png:apple-touch-icon.png',
    'png/icon-192.png:icon-192.png',
    'png/icon-512.png:icon-512.png',
  ],
  'apps/docs/src/assets': [
    'goodnight-web-icon.svg:app-icon.svg',
    'goodnight-web-lockup-light.svg:logo-lockup-light.svg',
    'goodnight-web-lockup-dark.svg:logo-lockup-dark.svg',
  ],
};
for (const [dir, files] of Object.entries(copies)) {
  for (const spec of files) {
    const [from, to] = spec.split(':') as [string, string];
    const target = join(repo, dir, to);
    await copyFile(join(brand, from), target);
    written.push(relative(repo, target));
  }
}

// The admin UI draws the logo inline so that theme tokens can colour it.
await write(
  join(repo, 'packages/server/admin-ui/src/features/layout/logo-shapes.gen.ts'),
  '// Generated by brand/scripts/build.ts. Do not edit.\n\n' +
    '/** viewBox of the square symbol. */\n' +
    `export const SYMBOL_VIEW_BOX = '${symbolViewBox()}';\n\n` +
    '/** viewBox of the lockup: the symbol and the wordmark. */\n' +
    `export const LOCKUP_VIEW_BOX = '${lockupViewBox()}';\n\n` +
    '/**\n' +
    ' * The lockup paths, back to front. The symbol is the `pillow` and `mark`\n' +
    ' * shapes; the eyes and the line around the pillow are holes in `mark`.\n' +
    ' */\n' +
    `export const LOGO_SHAPES: readonly {\n` +
    `  role: 'mark' | 'pillow' | 'goodnight' | 'web';\n` +
    `  d: string;\n}[] = ${JSON.stringify(lockupShapes(), null, 2)};\n`,
);


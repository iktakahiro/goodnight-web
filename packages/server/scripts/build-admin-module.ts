// Turns the prebuilt admin UI into one TypeScript module that the Worker
// bundles (docs/decisions/0004, option B). The source is the Vite build of
// the admin SPA in admin-ui/dist (`vite build --config admin-ui/vite.config.ts`).
//
// Usage: bun scripts/build-admin-module.ts [sourceDir]
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, join, relative, resolve } from 'node:path';

const packageDir = resolve(import.meta.dir, '..');
const sourceDir = resolve(packageDir, process.argv[2] ?? 'admin-ui/dist');
const outFile = join(packageDir, 'src/features/admin-ui/admin-files.gen.ts');

const CONTENT_TYPES: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8',
};

// Binary files (the favicon and the touch icon) are embedded as base64.
const BINARY_TYPES: Record<string, string> = {
  '.png': 'image/png',
  '.ico': 'image/x-icon',
};

const files: Record<
  string,
  { type: string; etag: string; body: string; encoding?: 'base64' }
> = {};

const walk = async (dir: string): Promise<void> => {
  const entries = await readdir(dir, { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(path);
      continue;
    }
    const extension = extname(path);
    const binaryType = BINARY_TYPES[extension];
    const type = CONTENT_TYPES[extension] ?? binaryType;
    if (!type) {
      throw new Error(`Unsupported admin file type: ${path}`);
    }
    const bytes = await readFile(path);
    const etag = `"${createHash('sha256').update(bytes).digest('base64url').slice(0, 22)}"`;
    const key = `/admin/${relative(sourceDir, path).split('\\').join('/')}`;
    files[key] = binaryType
      ? { type, etag, body: bytes.toString('base64'), encoding: 'base64' }
      : { type, etag, body: bytes.toString('utf8') };
  }
};

await walk(sourceDir);
if (!files['/admin/index.html']) {
  throw new Error(`No index.html in ${sourceDir}`);
}
await writeFile(
  outFile,
  `// Generated by scripts/build-admin-module.ts. Do not edit.\n` +
    `import type { AdminFile } from './admin-file.ts';\n\n` +
    `/** Prebuilt admin UI files keyed by URL path. */\n` +
    `export const adminFiles: Readonly<Record<string, AdminFile>> = ${JSON.stringify(files, null, 2)};\n`,
);
console.log(
  `admin-ui: wrote ${Object.keys(files).length} file(s) from ${relative(packageDir, sourceDir)}`,
);

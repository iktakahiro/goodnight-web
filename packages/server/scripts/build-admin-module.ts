// Turns the prebuilt admin UI into one TypeScript module that the Worker
// bundles (docs/decisions/0004, option B). Until the admin SPA exists, the
// source is admin-placeholder/.
//
// Usage: bun scripts/build-admin-module.ts [sourceDir]
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, join, relative, resolve } from 'node:path';

const packageDir = resolve(import.meta.dir, '..');
const sourceDir = resolve(packageDir, process.argv[2] ?? 'admin-placeholder');
const outFile = join(packageDir, 'src/features/admin-ui/admin-files.gen.ts');

const CONTENT_TYPES: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8',
};

const files: Record<string, { type: string; etag: string; body: string }> = {};

const walk = async (dir: string): Promise<void> => {
  const entries = await readdir(dir, { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(path);
      continue;
    }
    const type = CONTENT_TYPES[extname(path)];
    if (!type) {
      throw new Error(`Unsupported admin file type (text files only): ${path}`);
    }
    const body = await readFile(path, 'utf8');
    const etag = `"${createHash('sha256').update(body).digest('base64url').slice(0, 22)}"`;
    files[`/admin/${relative(sourceDir, path).split('\\').join('/')}`] = {
      type,
      etag,
      body,
    };
  }
};

await walk(sourceDir);
if (!files['/admin/index.html']) {
  throw new Error(`No index.html in ${sourceDir}`);
}
await writeFile(
  outFile,
  `// Generated by scripts/build-admin-module.ts. Do not edit.\n` +
    `import type { AdminFile } from './admin-file.ts';\n\n` +
    `/** Prebuilt admin UI files keyed by URL path. */\n` +
    `export const adminFiles: Readonly<Record<string, AdminFile>> = ${JSON.stringify(files, null, 2)};\n`,
);
console.log(
  `admin-ui: wrote ${Object.keys(files).length} file(s) from ${relative(packageDir, sourceDir)}`,
);
